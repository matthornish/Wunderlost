// Builds public/icons.svg (an SVG sprite) from the Lucide icons used by the app.
// Run after changing the list: npm run build:icons
const fs = require('fs');
const path = require('path');

const ICONS = [
  'inbox', 'star', 'calendar', 'calendar-days', 'calendar-check', 'user', 'users', 'search', 'list',
  'ellipsis', 'menu', 'plus', 'x', 'trash-2', 'bell', 'repeat', 'notebook-pen', 'list-checks',
  'folder-input', 'user-round', 'chevron-down', 'panel-right-close', 'log-out', 'check', 'sun', 'moon',
  'monitor', 'palette', 'lock-keyhole', 'settings', 'pencil', 'user-plus', 'eraser', 'door-open',
  'volume-2', 'shield', 'circle-alert', 'copy',
];

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const symbols = ICONS.map((name) => {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  return `<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`;
});

const out = `<svg xmlns="http://www.w3.org/2000/svg">
<!-- Lucide icons (ISC License, https://lucide.dev/license). Generated by scripts/build-icons.js; do not edit. -->
${symbols.join('\n')}
</svg>
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'icons.svg'), out);
console.log(`Wrote ${ICONS.length} icons to public/icons.svg`);
